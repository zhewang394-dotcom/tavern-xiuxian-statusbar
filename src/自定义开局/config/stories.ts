// ============ 自创剧本 ============
/**
 * 自创剧本的「分类」仅由宗门字段推导：宗门为「散修」（或空）→ 散修，其余 → 宗门。
 * 分类原本是给预设剧本做筛选展示用的，对自创剧本毫无意义——尤其「特殊」只属于
 * 预设的剧情剧本（绑定剧情物品/专属 UI）。自创剧本永不产生「特殊」，
 * 以免被误当作剧情剧本、把剧情物品错发给玩家。
 */
export function deriveCustomStoryKind(sect: string): StoryKind {
  const s = (sect || '').trim();
  return !s || s === '散修' ? '散修' : '宗门';
}

